#!/usr/bin/env python3
"""Opt-in keybind migration. Never remove a module still needed by the config."""
import os
import stat
import sys
import tempfile
from pathlib import Path

CAP = 262144
OLD = b'require("x-panel-bindings")'
NEW = b'require("hypr.x-panel-bindings")'
HEADER = b'-- Auto-generated by omarchy-x-panel.'


def read_regular(path):
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    try:
        st = os.fstat(fd)
        if not stat.S_ISREG(st.st_mode) or st.st_uid != os.getuid():
            raise ValueError('not an owned regular file')
        with os.fdopen(fd, 'rb', closefd=False) as stream:
            data = stream.read(CAP + 1)
        if len(data) > CAP:
            raise ValueError('config exceeds read limit')
        return data, stat.S_IMODE(st.st_mode)
    finally:
        os.close(fd)


def rewritten(data, enabled):
    out = []
    inserted = False
    for line in data.splitlines(keepends=True):
        if line.rstrip(b'\r\n') in (OLD, NEW):
            if enabled and not inserted:
                ending = b'\r\n' if line.endswith(b'\r\n') else b'\n'
                out.append(NEW + ending)
                inserted = True
        else:
            out.append(line)
    if enabled and not inserted:
        if data and not data.endswith(b'\n'):
            out.append(b'\n')
        out.append(NEW + b'\n')
    return b''.join(out)


def atomic_write(path, data, mode):
    fd, tmp = tempfile.mkstemp(prefix='.x-panel-write-', dir=path.parent)
    try:
        with os.fdopen(fd, 'wb') as stream:
            stream.write(data)
            stream.flush()
            os.fchmod(stream.fileno(), mode)
            os.fsync(stream.fileno())
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


def update(action, directory, plugin):
    directory = Path(directory)
    if directory.is_symlink() or not directory.is_dir():
        raise ValueError('unsafe or missing Hyprland directory')
    main = directory / 'hyprland.lua'
    module = directory / 'x-panel-bindings.lua'
    # Read the complete main config before touching either file. Missing,
    # oversized, special or unreadable main configs must retain the module.
    original, mode = read_regular(main)
    existing = None
    try:
        existing, _ = read_regular(module)
        if not existing.startswith(HEADER):
            raise ValueError('refusing to replace an unrecognized module')
    except FileNotFoundError:
        pass
    enabled = action == 'enable'
    target = rewritten(original, enabled)
    if enabled:
        # Encode the path as a Lua string; no shell or Lua code from path bytes.
        path = str(Path(plugin) / 'bin/omarchy-x-panel')
        if any(c in path for c in '\r\n\x00'):
            raise ValueError('unsupported plugin path')
        path = path.replace('\\', '\\\\').replace('"', '\\"')
        content = HEADER + b' Binds SUPER+SHIFT+X.\n' + (
            'hl.unbind("SUPER + SHIFT + X")\n'
            'o.bind("SUPER + SHIFT + X", "X Panel", "' + path + ' toggle")\n'
        ).encode()
        if existing != content:
            atomic_write(module, content, 0o600)
    if target != original:
        # A private recovery copy is created before replacing the config.
        fd, backup = tempfile.mkstemp(prefix='.x-panel-backup-', dir=directory)
        with os.fdopen(fd, 'wb') as stream:
            stream.write(original)
            stream.flush()
            os.fsync(stream.fileno())
        atomic_write(main, target, mode)
    if not enabled:
        # Reached only after a complete read and any required rewrite succeeded.
        try:
            module.unlink()
        except FileNotFoundError:
            pass


if __name__ == '__main__':
    try:
        if len(sys.argv) != 4 or sys.argv[1] not in ('enable', 'disable'):
            raise ValueError('expected enable/disable, config directory, plugin directory')
        update(*sys.argv[1:])
    except (OSError, ValueError):
        print('X Panel: keybind update failed; module retained. Check config access and retry.', file=sys.stderr)
        sys.exit(1)
